RAW_DATA:metadata:roadwork::STRING AS ROADWORK,
RAW_DATA:metadata:time_block::STRING AS TIMEBLOCK,
RAW_DATA:metadata:traffic_situation::STRING AS TRAFFIC_SITUATION,
