RAW_DATA:event_id::STRING  AS EVENT_ID,
RAW_DATA:sensor_id::STRING  AS SENSOR_ID,
RAW_DATA:city::STRING AS CITY,
SPLIT_PART(RAW_DATA:location::STRING,'|',1) AS AREA,
